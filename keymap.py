WIN_TO_NAME = {}
NAME_TO_WIN = {}
MAC_TO_NAME = {}
NAME_TO_MAC = {}
for _name, _win, _mac in _TABLE:
    if _win is not None:
        WIN_TO_NAME.setdefault(_win, _name)
        NAME_TO_WIN[_name] = _win
    if _mac is not None:
        MAC_TO_NAME.setdefault(_mac, _name)
        NAME_TO_MAC[_name] = _mac

